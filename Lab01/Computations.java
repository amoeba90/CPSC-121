public class Computations {
    
    public static void main(String[] args) {
        // Variable Declarations
        double var1, var2, sum, difference, product;

        // Assignments
        var1 = 1;
        var2 = 2;
        sum = var1 + var2;
        difference = var1 - var2;
        product = var1 * var2;

        System.out.println(var1 + " + " + var2 + " = " + sum);
        System.out.println(var1 + " - " + var2 + " = " + difference);
        System.out.println(var1 + " * " + var2 + " = " + product);
    }
}
